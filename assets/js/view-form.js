/* ============================================================
   view-form.js — complaint registration form.
   Mirrors the required/optional structure the business specified,
   with client-side validation that the server checks again.
   ============================================================ */
window.ViewForm = (function () {
  'use strict';

  var picked = { invoice_files: [], evidence_files: [] };

  function render(host) {
    picked = { invoice_files: [], evidence_files: [] };
    host.innerHTML = UI.skeleton(4);

    return API.master().then(function (m) {
      host.innerHTML =
        '<form id="cmpForm" class="grid" style="grid-template-columns:minmax(0,1fr);max-width:760px" novalidate>' +
          '<div id="formAlert"></div>' +

          section('Customer', 'Who is reporting the problem',
            field('Customer name', 'customer_name', '<input type="text" name="customer_name" required placeholder="Full name" autocomplete="name">') +
            field('Mobile number', 'customer_mobile', '<input type="tel" name="customer_mobile" required inputmode="numeric" placeholder="10-digit mobile" autocomplete="tel">') +
            field('Order number', 'order_number', '<input type="text" name="order_number" required placeholder="e.g. OAK-ORD-24180">') +
            field('Purchase date', 'purchase_date', '<input type="date" name="purchase_date" required max="' + new Date().toISOString().slice(0,10) + '">')
          ) +

          section('Product', 'Which chair the complaint is about',
            field('Chair type', 'chair_type',
              '<select name="chair_type" required>' + UI.options(m.chair_types, '', 'Select a chair type…') + '</select>')
          ) +

          section('Purchase source', 'Where the chair was bought',
            radios('purchase_source', m.purchase_sources)
          ) +

          section('The problem', 'What has gone wrong',
            radios('complaint_type', m.complaint_types) +
            field('Describe the complaint', 'description',
              '<textarea name="description" required placeholder="What is wrong, when it started, and anything the customer has already tried."></textarea>',
              'The more specific this is, the fewer follow-up calls the service team needs.')
          ) +

          section('Documents and evidence', 'Optional, but they speed up warranty checks',
            dropzone('invoice_files', 'Invoice file', 'PDF or image · up to ' + CONFIG.LIMITS.maxFiles + ' files, ' + CONFIG.LIMITS.maxInvoiceMB + ' MB each') +
            dropzone('evidence_files', 'Photos or video of the issue', 'Up to ' + CONFIG.LIMITS.maxFiles + ' files, ' + CONFIG.LIMITS.maxEvidenceMB + ' MB each')
          ) +

          section('Invoice and routing', 'Who billed it, and who handles it',
            field('Invoice generated by', 'invoice_generated_by',
              '<select name="invoice_generated_by" required>' + UI.options(m.invoice_entities, '', 'Select the billing entity…') + '</select>') +
            field('Priority', 'priority', '<select name="priority">' + UI.options(m.priorities, 'Medium') + '</select>') +
            field('Assign to (optional)', 'assigned_to',
              '<select name="assigned_to">' + UI.options(m.employees.map(function (e) {
                return { value: e.email, label: e.name + ' · ' + e.role };
              }), '', 'Leave unassigned') + '</select>')
          ) +

          '<div style="display:flex;gap:9px;flex-wrap:wrap;margin-bottom:40px">' +
            '<button type="submit" class="btn btn--primary" id="submitBtn">Register complaint</button>' +
            '<button type="reset" class="btn btn--ghost">Clear form</button>' +
          '</div>' +
        '</form>';

      UI.paintIcons(host);
      wire(host);
    });
  }

  function section(title, sub, inner) {
    return '<div class="card"><div class="card__head"><div><h3>' + title + '</h3><p>' + sub + '</p></div></div>' +
           '<div class="card__body">' + inner + '</div></div>';
  }

  function field(label, name, control, hint) {
    return '<label class="field"><span class="field__label">' + label +
      (control.indexOf('required') !== -1 ? ' <span class="req">*</span>' : '') + '</span>' +
      control + (hint ? '<span class="field__hint">' + hint + '</span>' : '') + '</label>';
  }

  function radios(name, list) {
    return '<div class="field"><span class="field__label">' +
      (name === 'purchase_source' ? 'Where did they buy it?' : 'Primary issue') +
      ' <span class="req">*</span></span><div class="radios" data-radios="' + name + '">' +
      list.map(function (v, i) {
        return '<label class="radio"><input type="radio" name="' + name + '" value="' + UI.esc(v) + '" required>' +
               '<span>' + UI.esc(v) + '</span></label>';
      }).join('') + '</div></div>';
  }

  function dropzone(name, label, hint) {
    return '<div class="field"><span class="field__label">' + label + '</span>' +
      '<label class="dropzone" data-zone="' + name + '">' +
        '<input type="file" multiple' + (name === 'evidence_files' ? ' accept="image/*,video/*"' : ' accept="image/*,application/pdf"') + '>' +
        '<span data-ico="file" style="display:block;width:20px;margin:0 auto 6px"></span>' +
        '<span data-label>Click to choose files</span>' +
      '</label><span class="field__hint">' + hint + '</span></div>';
  }

  function wire(host) {
    var form = host.querySelector('#cmpForm');

    // radio cards light up when chosen
    form.querySelectorAll('[data-radios]').forEach(function (group) {
      group.addEventListener('change', function () {
        group.querySelectorAll('.radio').forEach(function (r) {
          r.classList.toggle('is-on', r.querySelector('input').checked);
        });
      });
    });

    form.querySelectorAll('[data-zone]').forEach(function (zone) {
      var name = zone.dataset.zone;
      var input = zone.querySelector('input');
      var labelEl = zone.querySelector('[data-label]');
      var limitMb = name === 'evidence_files' ? CONFIG.LIMITS.maxEvidenceMB : CONFIG.LIMITS.maxInvoiceMB;

      ['dragover', 'dragleave', 'drop'].forEach(function (ev) {
        zone.addEventListener(ev, function (e) {
          e.preventDefault();
          zone.classList.toggle('is-over', ev === 'dragover');
          if (ev === 'drop') handle(e.dataTransfer.files);
        });
      });
      input.addEventListener('change', function () { handle(input.files); });

      function handle(fileList) {
        var files = Array.prototype.slice.call(fileList);
        if (!files.length) return;
        if (files.length > CONFIG.LIMITS.maxFiles) {
          return UI.toast('Up to ' + CONFIG.LIMITS.maxFiles + ' files here.', 'error');
        }
        var tooBig = files.filter(function (f) { return f.size > limitMb * 1024 * 1024; });
        if (tooBig.length) {
          return UI.toast('"' + tooBig[0].name + '" is over the ' + limitMb + ' MB limit.', 'error');
        }
        UI.loading(true);
        Promise.all(files.map(API.readFile))
          .then(function (payload) {
            picked[name] = payload;
            labelEl.textContent = files.length + ' file(s) ready · ' +
              files.map(function (f) { return f.name; }).join(', ');
          })
          .catch(function (e) { UI.toast(e.message, 'error'); })
          .finally(function () { UI.loading(false); });
      }
    });

    form.addEventListener('reset', function () {
      picked = { invoice_files: [], evidence_files: [] };
      setTimeout(function () {
        form.querySelectorAll('.radio').forEach(function (r) { r.classList.remove('is-on'); });
        form.querySelectorAll('[data-label]').forEach(function (l) { l.textContent = 'Click to choose files'; });
        form.querySelectorAll('[aria-invalid]').forEach(function (i) { i.removeAttribute('aria-invalid'); });
        document.getElementById('formAlert').innerHTML = '';
      }, 0);
    });

    form.addEventListener('submit', function (e) {
      e.preventDefault();
      submit(form, false);
    });
  }

  function submit(form, force) {
    var alertHost = document.getElementById('formAlert');
    alertHost.innerHTML = '';
    form.querySelectorAll('[aria-invalid]').forEach(function (i) { i.removeAttribute('aria-invalid'); });

    var data = {};
    new FormData(form).forEach(function (v, k) { data[k] = typeof v === 'string' ? v.trim() : v; });

    var missing = [];
    ['customer_name','customer_mobile','order_number','purchase_date','chair_type',
     'purchase_source','complaint_type','description','invoice_generated_by'].forEach(function (f) {
      if (!data[f]) missing.push(f);
    });
    if (missing.length) {
      missing.forEach(function (f) {
        var el = form.querySelector('[name="' + f + '"]');
        if (el) el.setAttribute('aria-invalid', 'true');
      });
      alertHost.innerHTML = '<div class="alert alert--error">Please complete the highlighted field' +
        (missing.length > 1 ? 's' : '') + ' before submitting.</div>';
      var first = form.querySelector('[aria-invalid]');
      if (first) first.scrollIntoView({ behavior: 'smooth', block: 'center' });
      return;
    }
    if (String(data.customer_mobile).replace(/\D/g, '').length < 10) {
      form.querySelector('[name="customer_mobile"]').setAttribute('aria-invalid', 'true');
      alertHost.innerHTML = '<div class="alert alert--error">Enter a valid 10-digit mobile number.</div>';
      return;
    }

    data.invoice_files = picked.invoice_files;
    data.evidence_files = picked.evidence_files;
    if (force) data.force = true;

    var btn = document.getElementById('submitBtn');
    btn.disabled = true;
    btn.textContent = 'Registering…';
    UI.loading(true);

    API.call('createComplaint', data, { dedupe: false })
      .then(function (res) {
        var id = res.data.complaint_id;
        UI.toast('Complaint ' + id + ' registered.');
        form.reset();
        form.dispatchEvent(new Event('reset'));
        alertHost.innerHTML = '<div class="alert alert--ok">Registered as <b>' + UI.esc(id) + '</b>. ' +
          '<button class="btn btn--sm btn--ghost" style="margin-left:8px" id="openNew">Open it</button></div>';
        var open = document.getElementById('openNew');
        if (open) open.addEventListener('click', function () { ViewComplaints.openDetail(id); });
      })
      .catch(function (e) {
        if (e.code === 'DUPLICATE_COMPLAINT') {
          alertHost.innerHTML = '<div class="alert alert--error">' + UI.esc(e.message) +
            '<div style="margin-top:9px;display:flex;gap:8px">' +
              '<button class="btn btn--sm btn--ghost" id="viewDup">View that complaint</button>' +
              '<button class="btn btn--sm btn--danger" id="forceNew">Register anyway</button>' +
            '</div></div>';
          var dupId = e.details && e.details.complaint_id;
          var vd = document.getElementById('viewDup');
          if (vd && dupId) vd.addEventListener('click', function () { ViewComplaints.openDetail(dupId); });
          var fn = document.getElementById('forceNew');
          if (fn) fn.addEventListener('click', function () { submit(form, true); });
        } else {
          alertHost.innerHTML = '<div class="alert alert--error">' + UI.esc(e.message) + '</div>';
        }
        alertHost.scrollIntoView({ behavior: 'smooth', block: 'center' });
      })
      .finally(function () {
        btn.disabled = false;
        btn.textContent = 'Register complaint';
        UI.loading(false);
      });
  }

  return { render: render };
})();
